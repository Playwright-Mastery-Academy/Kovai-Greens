export function productPhoto(variety: string): ProductPhotoSource | undefined {
  const normalized = variety.trim().replace(/\s+/g, ' ').toLowerCase();
  const key = normalized === 'cress' ? 'garden cress' : normalized;
  return Object.entries(productPhotos).find(([name]) => name.toLowerCase() === key)?.[1];
}
export function photoUrl(photo: ProductPhotoSource, width: number) {
  const url = new URL(photo.url);
  if (url.hostname === 'cdn.shopify.com') url.searchParams.set('width', String(width));
  return url.toString();
}
